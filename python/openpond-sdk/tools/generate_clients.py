"""Generate declared sync/async operation methods from the reviewed TS inventory."""
from __future__ import annotations
from runpy import run_path
import json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT.parents[1]/'packages/sdk/fixtures/python-foundation/operation-matrix.json'
DOCUMENT=json.loads(SOURCE.read_text())
FIXES={('OpenPondDatasetPreparationClient','operation_result'):('responseSchema','DatasetPreparationOperationResultSchema'),('OpenPondDatasetPreparationClient','candidates'):('responseSchema','DatasetPreparationCandidatePageSchema')}
for operation in DOCUMENT['operations']:
    if (operation['client'],operation['pythonMethod']) in FIXES:
        field,value=FIXES[(operation['client'],operation['pythonMethod'])];operation[field]=value
DEST=ROOT/'src/ponder_sdk'
(DEST/'operation-matrix.json').write_text(json.dumps(DOCUMENT,indent=2)+'\n')
GROUPS={'createTrainingClient':('training','Training'),'createModelProjectsClient':('models_client','Models'),'OpenPondLearningClient':('learning','Learning'),'createTrainingClient.postTraining':('post_training','PostTraining'),'OpenPondModelTasksetRunsClient':('evaluation_runs','EvaluationRuns'),'OpenPondDatasetWorkspaceClient':('datasets','Datasets'),'OpenPondDatasetPreparationClient':('dataset_preparations','DatasetPreparations'),'OpenPondToolLearningClient':('tool_learning','ToolLearning')}
SCHEMAS=run_path(str(DEST/'schema_asset.py'))['decode_schema_asset']((DEST/'schemas.json').read_bytes())['schemas']
def snake(v):return re.sub(r'(?<!^)(?=[A-Z])','_',v).lower()
def annotation(schema,namespace):
    if schema is None:return 'JsonValue'
    if schema=='LearningResourceSchemas[kind]':return 'models.LearningResource'
    if schema=='LearningResourcePage[kind]':return 'LearningPage'
    if schema.endswith('[]'):return 'list['+annotation(schema[:-2],namespace)+']'
    if '|' in schema:return 'Union['+', '.join(annotation(s,namespace) for s in schema.split('|'))+']'
    if schema not in SCHEMAS:raise ValueError('missing schema '+schema)
    return namespace+'.'+schema.removesuffix('Schema')
for group,(module,title) in GROUPS.items():
    lines=['# Generated by tools/generate_clients.py; do not hand-edit.','from __future__ import annotations','from typing import Union, cast','from . import inputs, models','from .wire import JsonValue','from .resources import Resource, AsyncResource, LearningPage','']
    tool_learning=group=='OpenPondToolLearningClient'
    if tool_learning:lines[-1:-1]=['from .tool_learning_resources import ToolLearningResource, AsyncToolLearningResource']
    ops=[op for op in DOCUMENT['operations'] if op['client']==group]
    for asynchronous in (False,True):
        lines.append('class '+('Async' if asynchronous else '')+title+'('+(('AsyncToolLearningResource' if asynchronous else 'ToolLearningResource') if tool_learning else ('AsyncResource' if asynchronous else 'Resource'))+'):')
        for op in ops:
            method=op['pythonMethod'];params=re.findall(r'\{(\w+)\}',op['path']);param_args=', '.join(snake(v)+': '+('int' if v=='revision' else 'str') for v in params)
            if tool_learning and op['pythonMethod']=='consultation':param_args=''
            args='self'+(', '+param_args if param_args else '')
            req=op['requestSchema']
            if req:args+=', input: '+annotation(req,'inputs')+(' | None = None' if op['httpMethod']=='GET' and not tool_learning else '')
            args+=', *, query: dict[str, JsonValue] | None = None'
            if tool_learning:pass
            elif method=='acceptance_group':args+=', expected: models.TrainingAcceptanceGroupReference | None = None'
            else:args+=', expected: models.ModelProjectImmutableRef' if method in ('candidate_decision','evaluation_tasks') else ', expected: models.ModelProjectImmutableRef | None = None'
            output=annotation(op['responseSchema'],'models')
            if method in ('candidate_decision','operation_result') or group=='createTrainingClient.postTraining' and method=='get':output+=' | None'
            lines.append('    '+('async ' if asynchronous else '')+'def '+method+'('+args+') -> '+output+':')
            lines.append('        """'+op['httpMethod']+' '+op['path']+'. '+('Current hosted route unavailable; no dispatch.' if 'verified_missing_hosted_endpoint' in op.get('classification','') else 'Read/reconcile; no mutation.' if op['httpMethod']=='GET' else 'Explicit operation; never automatically replayed.')+'"""')
            mapping='{'+', '.join(repr(v)+': '+snake(v) for v in params)+'}'
            if tool_learning and method=='consultation':mapping="{'installationId': input['installationId'], 'operationId': input['operationId']}"
            expression=('await ' if asynchronous else '')+'self._execute('+repr(group+'.'+method)+', '+mapping+', '+('input' if req else 'None')+', query, '+('None' if tool_learning else 'expected')+')'
            lines.append('        return cast('+repr(output)+', '+expression+')')
            lines.append('')
    (DEST/(module+'.py')).write_text('\n'.join(lines).rstrip()+'\n')
print(json.dumps({'operations':len(DOCUMENT['operations']),'parity':'sync+async','groups':len(GROUPS)}))
