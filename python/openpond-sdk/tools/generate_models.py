"""Generate public TypedDict/union models from the exported wire authority.

No handwritten algorithm schemas. JSON Schema runtime validation remains separate
because Zod custom refinements cannot be represented as Python annotations.
"""
from __future__ import annotations
from runpy import run_path
import json
import keyword
import re
import sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
DOCUMENT=run_path(str(ROOT/'src/ponder_sdk/schema_asset.py'))['decode_schema_asset']((ROOT/'src/ponder_sdk/schemas.json').read_bytes())
SCHEMAS=DOCUMENT['inputSchemas' if '--inputs' in sys.argv else 'schemas']
DEST=ROOT/'src/ponder_sdk'/('inputs' if '--inputs' in sys.argv else 'models')
DEST.mkdir(exist_ok=True)
for old in DEST.glob("*.py"):
    if old.read_text().startswith("# Generated"):old.unlink()
exports=[]
def type_structure(node):
    # Parsing policy changes runtime normalization, never a TypedDict shape.
    if isinstance(node,dict):return {key:type_structure(value) for key,value in node.items() if not (key=='x-openpond-object-policy' and isinstance(value,str))}
    if isinstance(node,list):return [type_structure(value) for value in node]
    return node

for schema_name,schema in sorted(SCHEMAS.items()):
    name=schema_name.removesuffix('Schema')
    if not name.isidentifier() or keyword.iskeyword(name):raise ValueError('invalid exported model name')
    definitions=[];known={};references={};structures={};counter=0
    def ref_name(ref):
        if not ref.startswith('#/'):raise ValueError('external schema reference unsupported')
        target=schema
        for part in ref[2:].split('/'):target=target[part.replace('~1','/').replace('~0','~')]
        if ref not in references:
            references[ref]=name+'Ref'+str(len(references)+1)
            emit(target,references[ref])
        return references[ref]
    def kind(node,hint):
        nonlocal_dummy=None
        if '$ref' in node:return repr(ref_name(node['$ref']))
        if 'const' in node:return 'Literal['+repr(node['const'])+']'
        if 'enum' in node:return 'Literal['+', '.join(repr(v) for v in node['enum'])+']'
        branches=node.get('anyOf',node.get('oneOf'))
        if branches:return 'Union['+', '.join(kind(v,hint+str(i)) for i,v in enumerate(branches))+']'
        typ=node.get('type')
        if isinstance(typ,list):return 'Union['+', '.join(kind({'type':t},hint) for t in typ)+']'
        if typ=='null':return 'None'
        if typ=='boolean':return 'bool'
        if typ=='integer':return 'int'
        if typ=='number':return 'Union[int, float]'
        if typ=='string':return 'str'
        if typ=='array':return 'list['+kind(node.get('items',{}),hint+'Item')+']'
        if typ=='object' or 'properties' in node:
            if not node.get('properties'):return 'dict[str, '+kind(node.get('additionalProperties',{}) if isinstance(node.get('additionalProperties'),dict) else {},hint+'Value')+']'
            signature=json.dumps(type_structure(node),sort_keys=True,separators=(',',':'))
            if signature in structures:return repr(structures[signature])
            structures[signature]=hint
            emit(node,hint)
            return repr(hint)
        return 'JsonValue'
    def emit(node,title):
        if title in known:return
        known[title]=True
        if (node.get('type')=='object' or 'properties' in node) and node.get('properties'):
            fields=[];required=node.get('required',[])
            for i,(key,value) in enumerate(node['properties'].items()):
                annotation=kind(value,title+re.sub(r'[^A-Za-z0-9]','',key.title())+str(i))
                fields.append('    '+repr(key)+': '+('Required' if key in required else 'NotRequired')+'['+annotation+'],')
            definitions.append(title+' = TypedDict('+repr(title)+', {\n'+'\n'.join(fields)+'\n})\n')
        else:definitions.append(title+': TypeAlias = '+kind(node,title+'Value')+'\n')
    emit(schema,name)
    module=re.sub(r'(?<!^)(?=[A-Z])','_',name).lower()
    code='''# Generated by tools/generate_models.py; do not hand-edit.\nfrom __future__ import annotations\nfrom typing import Literal, Union, TypeAlias, TypedDict\nfrom typing_extensions import NotRequired, Required\nfrom ..wire import JsonValue\n\n'''+ '\n'.join(definitions)
    if len(code.splitlines())>1900:raise ValueError(f'{name} requires splitting generated model module')
    (DEST/(module+'.py')).write_text(code)
    exports.append('from .'+module+' import '+name)
(DEST/'__init__.py').write_text('# Generated public wire request/result models.\n'+'\n'.join(exports)+'\n')
print(json.dumps({'generatedModels':len(exports),'maximumLines':max(len(p.read_text().splitlines()) for p in DEST.glob('*.py'))}))
