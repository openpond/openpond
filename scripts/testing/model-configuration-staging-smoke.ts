import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { homedir } from "node:os";
import { join } from "node:path";
import { createModelProjectsClient, createModelProjectSaveRequest, OpenPondModelProjectApiError } from "openpond-sdk/model-projects";
import { OpenPondLearningClient, learningRef } from "openpond-sdk/learning";
import { OpenPondTasksetCatalogClient, OpenPondTasksetCatalogError } from "openpond-sdk/taskset-catalog";

// HTTP-only verification. Uses a previously reviewed batch and never starts a
// model, grading job, or training job. Credentials remain in process memory.
const baseUrl = "https://staging-api.openpond.ai";
const accounts = JSON.parse(await readFile(join(homedir(), ".openpond", "config.json"), "utf8")) as { accounts?: Array<{ baseUrl?: string; apiKey?: string }> };
const apiKey = accounts.accounts?.find((account) => [baseUrl, "https://staging.openpond.ai"].includes(account.baseUrl?.replace(/\/+$/, "") ?? ""))?.apiKey;
assert(apiKey, "A saved staging CLI profile is required.");
const response = await fetch(`${baseUrl}/v1/teams`, { headers: { authorization: `Bearer ${apiKey}` }, signal: AbortSignal.timeout(30_000) });
assert(response.ok, `Workspace lookup failed: HTTP ${response.status}`);
const teams = await response.json() as { teams: Array<{ id: string; isPersonalDefault: boolean }> };
const scope = teams.teams.find((team) => team.isPersonalDefault)?.id;
assert(scope, "A personal staging workspace is required.");
const headers = { authorization: `Bearer ${apiKey}`, "X-OpenPond-Team-Id": scope };
const models = createModelProjectsClient({ baseUrl, headers });
const learning = new OpenPondLearningClient({ baseUrl, apiKey, scope });
const catalog = new OpenPondTasksetCatalogClient({ baseUrl, apiKey, teamId: scope });
const batch = await learning.get("batch", "learning-smoke-9c58618a-ee03-4208-b7d1-73cc45636067:batch");
const binding = await learning.get("binding", batch.rewardBinding.id, batch.rewardBinding.revision);
assert.deepEqual(learningRef(binding), batch.rewardBinding);
const candidates = await models.configurationCandidates();
assert(candidates.some((candidate) => candidate.available), "No hosted starting models are available.");
const id = `model-configuration-smoke-${crypto.randomUUID()}`;
const editable = { id, profileId: scope, name: "Staging configuration smoke", objective: null, defaultBaseModel: null, defaultDestinationId: null, trainingSetup: { rewardBindingRef: learningRef(binding) } };
const request = await createModelProjectSaveRequest(editable, 0);
const checked = await models.checkConfiguration(request);
assert(checked.canSave);
assert(checked.deferred.includes("taskset"));
const copies = await Promise.all(Array.from({ length: 3 }, () => models.saveConfiguration(request)));
assert.equal(new Set(copies.map((project) => project.id)).size, 1);
assert.deepEqual(copies[0]!.trainingSetup.rewardBindingRef, batch.rewardBinding);
const saved = copies[0]!;
const revisedRequest = await createModelProjectSaveRequest({ ...editable, name: "Staging configuration smoke revised" }, saved.revision);
const revised = await models.saveConfiguration(revisedRequest);
assert.equal(revised.revision, saved.revision + 1);
assert.deepEqual(await models.saveConfiguration(request), saved);
await assert.rejects(models.saveConfiguration(await createModelProjectSaveRequest({ ...editable, name: "Stale configuration" }, saved.revision)), (error: unknown) => error instanceof OpenPondModelProjectApiError && error.status === 409);
const attached = await Promise.all(Array.from({ length: 3 }, () => learning.publishBatch({ batchId: batch.id, modelProjectId: saved.id })));
assert.equal(new Set(attached.map((receipt) => receipt.tasksetId)).size, 1);
const receipt = attached[0]!;
const detail = await models.get(saved.id);
assert.equal(detail.resources.filter((resource) => resource.kind === "taskset_release" && resource.ref.id === receipt.tasksetId).length, 1);
const configured = await models.saveConfiguration(await createModelProjectSaveRequest({ ...editable, name: revised.name, trainingSetup: { rewardBindingRef: batch.rewardBinding, tasksetRef: { id: receipt.releaseId, revision: receipt.revision, contentHash: receipt.contentHash }, tasksetRelease: { id: receipt.releaseId, contentHash: receipt.contentHash } } }, revised.revision));
assert.equal(configured.trainingSetup.tasksetRef?.contentHash, receipt.contentHash);
assert.deepEqual((await models.get(saved.id)).project.trainingSetup.rewardBindingRef, batch.rewardBinding);
const page = await catalog.list({ modelProjectId: saved.id, limit: 1 });
assert.equal(page.items.length, 1);
assert.equal(page.nextCursor, null);
assert.equal(page.items[0]!.id, receipt.tasksetId);
assert.deepEqual((await catalog.get(receipt.tasksetId)).release, configured.trainingSetup.tasksetRef);
assert.deepEqual(await catalog.resolve(configured.trainingSetup.tasksetRef!), page.items[0]);
assert.equal("tasks" in page.items[0]!, false);
assert.equal(JSON.stringify(page).includes("r2://"), false);
await assert.rejects(catalog.resolve({ ...configured.trainingSetup.tasksetRef!, contentHash: "f".repeat(64) }), (error: unknown) => error instanceof OpenPondTasksetCatalogError && error.status === 404);
process.stdout.write(JSON.stringify({ status: "PASS", modelId: saved.id, tasksetId: receipt.tasksetId, revision: configured.revision, checks: ["Reward before Tasks", "retry receipt", "revision conflict", "concurrent publication", "exact attachment", "catalog metadata and exact release"] }) + "\n");
