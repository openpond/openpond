import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const source = new URL("../apps/web/src/styles/theme.css", import.meta.url);
const target = new URL("../packages/contracts/src/ui-theme.generated.ts", import.meta.url);
const css = readFileSync(source, "utf8");
const blocks = [...css.matchAll(/(?:^|\n)(:root[^{}]*)\{([^{}]*)\}/g)];
if (blocks.length !== 2) throw new Error("Theme must contain exactly the dark and light root palettes.");
const values = blocks.map(block => Object.fromEntries([...block[2].matchAll(/(--[\w-]+):\s*([^;]+);/g)].map(m => [m[1], m[2].trim()])));
const dark = values[0];
const light = { ...dark, ...values[1] };
function resolve(palette) {
  const result = { ...palette };
  for (const key of Object.keys(result)) {
    const seen = new Set([key]);
    let match;
    while ((match = /^var\((--[\w-]+)\)$/.exec(result[key]))) {
      if (seen.has(match[1]) || !(match[1] in result)) throw new Error(`Invalid theme alias: ${key}`);
      seen.add(match[1]);
      result[key] = result[match[1]];
    }
  }
  return result;
}
const content = `// Generated by scripts/generate-ui-theme.mjs from apps/web/src/styles/theme.css. Do not edit.\nexport const UI_THEME_CSS = ${JSON.stringify(css)};\nexport const UI_THEME_COLORS = ${JSON.stringify({ dark: resolve(dark), light: resolve(light) }, null, 2)} as const;\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== content) throw new Error("Generated theme is stale. Run pnpm theme:generate.");
} else writeFileSync(target, content);
console.log(`Theme ${process.argv.includes("--check") ? "verified" : "generated"}: ${fileURLToPath(target)}`);
