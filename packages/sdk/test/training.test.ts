      const changed = structuredClone(f.result);
      if (mode === "truncated") {
        const removed = changed.captures.pop();
        changed.outcomes.find((row: { promptId: string; variantId: string }) => row.promptId === removed.promptId && row.variantId === removed.variantId).captureCount -= 1;
      }
      if (mode === "token") changed.captures[0].tokenId += 1;
