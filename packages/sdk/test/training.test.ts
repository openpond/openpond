      schemaVersion: "openpond.trainingPreparationRequest.v1",
      teamId: "team-a",
      operationId: "manual-preparation-1",
      projectId: null,
      configuration: { id: "hosted-project-1", expectedRevision: 3, expectedEtag: HASH },
